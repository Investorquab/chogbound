export type StatName = 'GRIT' | 'PUNCH' | 'SWIFT' | 'NERVE';
export type Stats = Record<StatName, number>;
export type TraitAttribute = { trait_type: string; value: string };
export type TraitToken = { name: string; attributes: TraitAttribute[] };
export type VoiceClass = 'fierce' | 'smug' | 'hustler' | 'hungry' | 'gloom' | 'neutral';
export type AuraClass = 'scorch' | 'gust' | 'vanish' | 'calm-glow' | 'none';
export type AccessoryClass = 'pump' | 'lucky-flip' | 'sidekick' | 'trinket' | 'none';
export type CoreMove = 'Headbutt' | 'Quick Feet' | 'Iron Hide';
export type SignatureMove = 'Laser Stare' | 'Scan' | 'Charm' | 'Stare Down' | 'Chaos Gaze';
export type Move = CoreMove | SignatureMove;
export type Temperament = 'Feisty' | 'Cool' | 'Wild';
export type Risk = 'Safe' | 'Even' | 'Gamble';
export type Plan = { temperament: Temperament; move: Move; risk: Risk };
export type Fighter = {
  tokenId: string;
  name: string;
  stats: Stats;
  voiceClass: VoiceClass;
  aura: AuraClass;
  accessory: AccessoryClass;
  signature: SignatureMove | null;
  tier: string;
};
export type Side = 'a' | 'b';
export type FightOutcome = 'hit' | 'crit' | 'miss' | 'dodge';
export type FightAction = 'opening' | 'attack' | 'burn' | 'heal';
export type FightEvent = {
  n: number;
  round: number;
  actor: Side;
  action: FightAction;
  move: Move | 'Scorch' | 'Calm Glow' | 'Scan';
  outcome: FightOutcome;
  damage: number;
  heal: number;
  hp_after: { a: number; b: number };
  procs: string[];
  narration_key: string;
  vars: Record<string, string | number | boolean>;
};
export type FightSummary = {
  seed: string;
  winner: Side;
  ko: boolean;
  rounds: number;
  totals: { a: number; b: number };
  final_hp: { a: number; b: number };
  upset: boolean;
};
export type SimResult = { events: FightEvent[]; summary: FightSummary };
export type TraitBonus = { stat: StatName; amount: number; trait: string; value: string; reason: string };
export type StatResult = { stats: Stats; bonuses: TraitBonus[]; classes: { body: string; eyes: string; head: string; mouth: VoiceClass; aura: AuraClass; accessory: AccessoryClass }; signature: SignatureMove | null; legendaryKit?: string };
